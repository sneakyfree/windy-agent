def cmd_go(args: Any) -> None:
    """Hatch the agent: open the Windy hatch ceremony in the browser (ADR-059).

    The agent is born in the cloud and stays there; this terminal just
    opens the page and waits. There is no terminal hatch any more —
    ``WINDY_HATCH_VIA_HUB`` is ignored.
    """
    from windyfly import hub_hatch
    from windyfly.observability import disclosure

    disclosure.maybe_show(lambda line: console.print(f"[dim]{line}[/dim]"))
    force = bool(getattr(args, "force", False))
    if force:
        os.environ["_WINDYFLY_FORCE_HATCH"] = "1"

    rc = hub_hatch.go(
        console,
        force=force,
        open_browser=(lambda _url: None) if getattr(args, "no_browser", False) else None,
    )
    if rc:
        sys.exit(rc)

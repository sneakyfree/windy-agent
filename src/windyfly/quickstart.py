# The agent's identity lives in .env. Re-running `windy go` rewrites .env
# from scratch, which blanked ETERNITAS_PASSPORT_TOKEN — the next hatch then
# minted a SECOND passport for the same agent (Eternitas caps auto-hatch at
# 5/hour, and the first passport was orphaned). Keep these across rewrites.
_IDENTITY_KEYS = ("ETERNITAS_PASSPORT", "ETERNITAS_PASSPORT_TOKEN")


def _read_env_values(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                values[k.strip()] = v.strip()
    except OSError:
        pass
    return values


def _write_env_keeping_identity(env_lines: list[str]) -> None:
    env_file = PROJECT_ROOT / ".env"
    kept = {
        k: v for k, v in _read_env_values(env_file).items()
        if k in _IDENTITY_KEYS and v
    }
    out: list[str] = []
    for line in env_lines:
        key = line.split("=", 1)[0] if "=" in line else ""
        if key in kept:
            out.append(f"{key}={kept.pop(key)}")
        else:
            out.append(line)
    out.extend(f"{k}={v}" for k, v in kept.items())
    from windyfly.platform import write_private_text

    write_private_text(env_file, "\n".join(out) + "\n")



def write_quick_config(
    env_var: str,
    api_key: str,
    model: str,
    preset: str = "buddy",
) -> None:
    """Write .env and windyfly.toml for quickstart."""
    from windyfly.setup_wizard import PRESETS, PROVIDERS

    preset_data = PRESETS.get(preset, PRESETS["buddy"])
    data_dir = PROJECT_ROOT / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    # Build .env
    env_lines = [
        "# Windy Fly — generated by `windy go`",
        f"DEFAULT_MODEL={model}",
        "",
        "# LLM Providers",
    ]
    for provider in PROVIDERS:
        if provider["key"] == env_var:
            env_lines.append(f"{provider['key']}={api_key}")
        else:
            env_lines.append(f"{provider['key']}=")

    env_lines.extend([
        "",
        "# Database",
        "WINDYFLY_DB_PATH=data/windyfly.db",
        "",
        "# Logging",
        "LOG_LEVEL=INFO",
        "",
        "# Matrix / Windy Chat (optional)",
        "MATRIX_HOMESERVER=https://chat.windychat.ai",
        "# MATRIX_BOT_USER: leave empty; the agent's own @agent_<passport> id comes from its passport",
        "MATRIX_BOT_USER=",
        "MATRIX_BOT_TOKEN=",
        "MATRIX_BOT_PASSWORD=",
        "",
        "# Windy Pro API (optional)",
        "WINDY_API_URL=http://localhost:8098",
        "WINDY_JWT=",
        "",
        "# Eternitas (agent identity: passport, birth certificate, trust)",
        eternitas_env_line(),
    ])

    _write_env_keeping_identity(env_lines)

    # Build windyfly.toml
    agent_name = os.environ.get("WINDYFLY_AGENT_NAME", "Windy Fly")
    toml_content = f"""[agent]
name = "{agent_name}"
default_model = "{model}"
max_context_tokens = 8000
max_response_tokens = 2000
temperature = 0.7

[memory]
db_path = "data/windyfly.db"
max_episodes_per_context = 20
max_nodes_per_context = 10

[personality]
soul_path = "SOUL.md"
preset = "{preset}"
humor_level = {preset_data.get('humor', 5)}
formality = {preset_data.get('formality', 5)}
proactivity = 5
verbosity = 5
reasoning_depth = 6
autonomy = 3
epistemic_strictness = 5

[costs]
daily_budget_usd = 5.0
warn_at_usd = 0.50

[matrix]
homeserver = "https://chat.windychat.ai"
# No bot_user: each agent's Matrix id is its own @agent_<passport>, minted at
# hatch from its passport and confirmed at login. Set bot_user only for a
# self-hosted password login.

[windy_api]
base_url = "http://localhost:8098"
"""
    (PROJECT_ROOT / "windyfly.toml").write_text(toml_content, encoding="utf-8")



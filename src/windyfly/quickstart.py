# ═══════════════════════════════════════════════════════════════════════
# Key detection — identify provider from key format
# ═══════════════════════════════════════════════════════════════════════

# Single source of truth: windyfly.provider_defaults (Sprint 2 —
# this table used to be one of THREE divergent copies; see that
# module's docstring, imported at top of file). Dict shapes preserved
# for downstream callers.
KEY_PATTERNS: list[dict[str, str]] = [
    {
        "prefix": p["key_prefix"],
        "env_var": p["env_var"],
        "provider": p["name"],
        "model": p["default_model"],
        "url": p["url"],
    }
    for p in key_detection_order()
]

# Providers the user can choose if we can't auto-detect
PROVIDER_MENU = [
    {
        "name": p["name"],
        "env_var": p["env_var"],
        "model": p["default_model"],
        "url": p["url"],
    }
    for p in PROVIDER_DEFAULTS
]


def detect_provider(key: str) -> dict[str, str] | None:
    """Identify the provider from an API key's prefix.

    Returns a dict with provider, env_var, model, url — or None if
    the key format isn't recognized.
    """
    key = key.strip()
    for pattern in KEY_PATTERNS:
        if key.startswith(pattern["prefix"]):
            return pattern
    return None


